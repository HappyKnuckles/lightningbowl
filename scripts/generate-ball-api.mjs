// Generates the ball API types from the spec the ball API repo commits (lightningbowl-ball-api/openapi.json).
//
//   npm run generate:ball-api                         spec from the ball API's main branch
//   BALL_API_REF=<branch> npm run generate:ball-api   spec from a ball API branch, e.g. before it's deployed
//   BALL_API_SPEC=<url or path> npm run generate:ball-api
//   npm run generate:ball-api -- --check              fails if the committed types differ from the spec
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";
import prettier from "prettier";

const OUTPUT = "src/app/core/models/generated/ball-api.d.ts";
const ref = process.env.BALL_API_REF || "main";
const spec = process.env.BALL_API_SPEC || `https://raw.githubusercontent.com/HappyKnuckles/lightningbowl-ball-api/${ref}/openapi.json`;
const check = process.argv.includes("--check");

const source = /^https?:\/\//.test(spec) ? new URL(spec) : new URL(`file://${resolve(spec)}`);
const banner = "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n";
const generated = await prettier.format(banner + astToString(await openapiTS(source)), {
  ...(await prettier.resolveConfig(OUTPUT, { editorconfig: true })),
  filepath: OUTPUT,
});

if (check) {
  if (readFileSync(OUTPUT, "utf8") !== generated) {
    console.error(`${OUTPUT} is out of date with ${spec}. Run npm run generate:ball-api.`);
    process.exit(1);
  }
  console.log(`${OUTPUT} matches ${spec}.`);
} else {
  writeFileSync(OUTPUT, generated);
  console.log(`Wrote ${OUTPUT} from ${spec}.`);
}
